export type TKey = keyof typeof T;
const IDX: Record<Lang, number> = { uk: 0, ru: 1, en: 2 };

export function useT() {
  const { s } = useStore();
  const lang: Lang = s.lang ?? 'uk';
  const t = (k: TKey) => T[k][IDX[lang]];
  const tr = (v: L | undefined) => (v == null ? '' : typeof v === 'string' ? v : v[lang]);
  return { t, tr, lang };
}

export const l = (uk: string, ru: string, en: string): L => ({ uk, ru, en });
